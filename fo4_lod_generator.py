# ── LOD texture downscaling (match real FO4's smaller LOD-specific textures) ──
# Real FO4 assets use dedicated, much smaller textures for their real-mesh LOD
# levels — e.g. vanilla BlastedForestBurntTreeUpright01's LOD1 references a
# small shared 'LOD/Trees/BlastedForestTrunksLOD_d.dds' atlas, not its full
# resolution hero texture, and only the farthest billboard level gets its own
# separate (also small) texture. Until this was added, every LOD generated by
# this add-on only decimated geometry and left the LOD pointing at the exact
# same full-resolution material as the source — the in-game LOD saved
# triangle/vertex cost but NONE of the texture memory/bandwidth cost LODs are
# also meant to save.

def _nearest_pow2(n: int) -> int:
    """Round n to the nearest power of two (minimum 64 — FO4's smallest
    common texture size). FO4/DDS textures are conventionally power-of-two."""
    n = max(64, int(n))
    lower = 1 << (n.bit_length() - 1)
    upper = lower << 1
    return upper if (n - lower) > (upper - n) else lower


def _is_game_data_folder(textures_root: str) -> bool:
    """True when *textures_root* is the Textures folder of a game Data folder
    (the configured FO4 Data path, or any folder holding Fallout4.esm).
    LOD textures must go into the mod being built, never into the game."""
    data_dir = os.path.normcase(os.path.normpath(os.path.dirname(textures_root)))
    try:
        from . import preferences as _prefs_mod
        prefs = _prefs_mod.get_preferences()
        game = (getattr(prefs, "fo4_game_data_path", "") or "").strip() if prefs else ""
        if game and os.path.normcase(os.path.normpath(bpy.path.abspath(game))) == data_dir:
            return True
    except Exception:
        pass
    return os.path.isfile(os.path.join(data_dir, "Fallout4.esm"))


def _lod_texture_output_dir(src_path: str, out_subdir: str = "LOD",
                            textures_root: str = "") -> str:
    """Directory to write a downscaled LOD texture into, mirroring real FO4's
    ``Textures\\LOD\\...`` convention (see the vanilla
    ``LOD/Trees/BlastedForestTrunksLOD_d.dds`` reference in the comment
    above) -- confirmed as a real bug: this used to be
    ``os.path.join(os.path.dirname(src_path), out_subdir)``, which drops a
    ``LOD`` folder next to wherever the source texture happens to live (e.g.
    ``.../Textures/Architecture/SomeBuilding/LOD/``). FO4 and every real mod
    instead keeps ONE ``LOD`` folder directly under the mod's ``Textures``
    root and mirrors the rest of the source's subpath underneath it (e.g.
    ``.../Textures/LOD/Architecture/SomeBuilding/``) -- that's also where
    Creation Kit and the game engine actually look for object-LOD textures,
    so the old layout produced files nothing in the pipeline would find.

    Finds the last path segment named exactly "textures" (case-insensitive,
    since Windows/MO2 paths are case-insensitive) and rebuilds the LOD
    output path relative to that root. Falls back to the old
    dirname-adjacent behaviour only if no "Textures" segment is found (e.g.
    a texture loaded from somewhere outside any recognizable mod/game
    folder structure), since there's nothing better to anchor to there.
    """
    norm = os.path.normpath(src_path)
    parts = norm.split(os.sep)
    tex_idx = next(
        (i for i in range(len(parts) - 1, -1, -1) if parts[i].lower() == "textures"),
        None,
    )
    if tex_idx is None:
        if textures_root:
            return os.path.join(textures_root, out_subdir)
        return os.path.join(os.path.dirname(src_path), out_subdir)

    # *textures_root* (the mod's own Textures folder) wins over the folder the
    # source texture was loaded from, which is often the game's own Data.
    textures_root = textures_root or os.sep.join(parts[:tex_idx + 1])
    rel_parts = [p for p in parts[tex_idx + 1:-1] if p]  # everything between Textures/ and the filename
    # Re-running LOD generation on the same object reuses its material, whose
    # texture node by then already points at THIS function's own previous
    # output (e.g. ".../Textures/LOD/Landscape/Plants/x.png") -- using that
    # as the next call's src_path re-derives a rel_subdir that already
    # starts with "LOD" and inserting out_subdir again nests it one folder
    # deeper every re-run (.../Textures/LOD/LOD/..., then LOD/LOD/LOD/...).
    # Confirmed directly from a real exported NIF referencing
    # "textures\lod\lod\gsfungusgroup02bramble01_d.dds". Strip any leading
    # out_subdir segment(s) already present before adding this call's own.
    while rel_parts and rel_parts[0].lower() == out_subdir.lower():
        rel_parts.pop(0)
    rel_subdir = os.sep.join(rel_parts)
    return os.path.join(textures_root, out_subdir, rel_subdir) if rel_subdir else os.path.join(textures_root, out_subdir)


def create_lod_textures(lod_objects: list, scale_factor: float = 0.25,
                         out_subdir: str = "LOD", textures_root: str = "") -> tuple:
    """Give every object in *lod_objects* a shared, downscaled copy of the
    source's textures instead of the full-resolution original.

    Every object in *lod_objects* gets the SAME downscaled image per unique
    source texture — matching real FO4 LOD atlases, which are shared across
    every real-mesh LOD level of an asset (only the farthest billboard level
    gets its own separate texture, handled separately by
    :func:`generate_billboard_lod`). The first LOD object whose texture node
    references a given source file creates the downscaled image/file; every
    later object referencing that same source file reuses it, so this never
    saves more than one new file per original texture no matter how many LOD
    levels are passed in.

    Each object's material is made single-user first, so downscaling a LOD's
    textures never touches the source mesh's own (still full-resolution)
    material — ``duplicate()``/``generate_lod_mesh`` share the source's
    material by default until something makes it single-user.

    Saved as PNG (not DDS) deliberately: export_textures_for_object /
    write_bgsm's existing texture-export pipeline already converts any
    non-DDS source to DDS via texconv/NVTT at actual export time, so this
    does not need its own separate DDS-conversion path or texconv
    configuration to be useful immediately after generation.

    Returns (bool success, str message).
    """
    if not lod_objects:
        return False, "No LOD objects provided"

    shared_cache: dict = {}
    processed = 0
    skipped = []

    for lod_obj in lod_objects:
        if lod_obj is None or lod_obj.type != 'MESH' or not lod_obj.data.materials:
            continue
        for slot in lod_obj.material_slots:
            mat = slot.material
            if mat is None or not getattr(mat, "use_nodes", False):
                continue
            if mat.users > 1:
                mat = mat.copy()
                slot.material = mat
            # No wind or glow on a LOD: drop the flags and the glow nodes
            # before downscaling, so no _g texture is written either.
            strip_lod_material(mat)

            for node in mat.node_tree.nodes:
                if node.type != 'TEX_IMAGE' or not node.image:
                    continue
                img = node.image

                # Re-running LOD generation on an object whose material was
                # already downscaled by a previous run used to treat that
                # already-small LOD image as a fresh "source" and downscale
                # it AGAIN -- compounding quality loss on every re-run (this
                # is the same root cause behind an earlier real incident: a
                # mod-wide batch of ~1,268 degraded 64x64 textures from
                # repeated LOD generation attempts). Images this function
                # itself created are tagged fo4_lod_generated=True; skip
                # touching them further -- they're already the right size.
                if img.get("fo4_lod_generated"):
                    key = os.path.normcase(os.path.normpath(
                        bpy.path.abspath(img.filepath))) if img.filepath else img.name
                    shared_cache.setdefault(key, img)
                    node.image = img
                    processed += 1
                    continue

                try:
                    src_path = bpy.path.abspath(img.filepath) if img.filepath else ""
                except Exception:
                    src_path = ""
                if not src_path or not os.path.isfile(src_path):
                    skipped.append(f"'{node.name}' on '{lod_obj.name}': no source file on disk")
                    continue

                key = os.path.normcase(os.path.normpath(src_path))
                if key in shared_cache:
                    node.image = shared_cache[key]
                    processed += 1
                    continue

                # Force a reload before trusting img.size -- a newly-linked or
                # not-yet-fully-loaded Blender Image can report a stale/
                # placeholder size (much smaller than the real file) until
                # something forces it to actually read pixel data. Trusting
                # that stale size here used to silently bake a tiny (as low
                # as the 64x64 floor) LOD texture from a real 4096x4096
                # source -- confirmed as a real bug from a user report: the
                # resulting texture was so small it read as a flat white
                # blob in-game instead of the actual image.
                try:
                    img.reload()
                except Exception:
                    pass

                src_w, src_h = img.size[0], img.size[1]
                if src_w <= 0 or src_h <= 0:
                    skipped.append(
                        f"'{node.name}' on '{lod_obj.name}': image '{img.name}' "
                        f"reports {src_w}x{src_h} even after reload -- skipped "
                        "rather than risk baking a broken LOD texture"
                    )
                    continue

                new_w = _nearest_pow2(src_w * scale_factor)
                new_h = _nearest_pow2(src_h * scale_factor)
                if new_w >= src_w and new_h >= src_h:
                    shared_cache[key] = img  # already small enough — share as-is
                    node.image = img
                    processed += 1
                    continue

                if not textures_root:
                    _parts = os.path.normpath(src_path).split(os.sep)
                    _ti = next((i for i in range(len(_parts) - 1, -1, -1)
                                if _parts[i].lower() == "textures"), None)
                    if _ti is not None and _is_game_data_folder(os.sep.join(_parts[:_ti + 1])):
                        skipped.append(
                            f"'{node.name}' on '{lod_obj.name}': source texture is in the game's "
                            "Data folder -- set a Mod Folder so the LOD texture goes into your mod"
                        )
                        continue

                stem = os.path.splitext(os.path.basename(src_path))[0]
                new_img = img.copy()
                new_img.name = f"{stem}_LOD"
                new_img.scale(new_w, new_h)

                out_dir = _lod_texture_output_dir(src_path, out_subdir, textures_root)
                os.makedirs(out_dir, exist_ok=True)
                out_path = os.path.join(out_dir, f"{stem}.png")
                new_img.filepath_raw = out_path
                new_img.file_format = 'PNG'
                new_img.save()
                # FO4 cannot load PNG: convert to DDS beside it and point the
                # material at the DDS so the NIF and .bgsm reference it.
                try:
                    from . import nvtt_helpers as _nv
                    _dds = os.path.splitext(out_path)[0] + ".dds"
                    _slot = "Normal" if stem.lower().endswith("_n") else (
                        "Specular" if stem.lower().endswith("_s") else "Diffuse")
                    _ok_dds, _dds_msg = _nv.NVTTHelpers.convert_to_dds(out_path, _dds, slot=_slot)
                except Exception as _exc:
                    _ok_dds, _dds_msg = False, str(_exc)
                if _ok_dds and os.path.isfile(_dds):
                    new_img.filepath = _dds
                    try:
                        os.remove(out_path)
                    except OSError:
                        pass
                else:
                    skipped.append(f"{stem}: DDS conversion failed ({_dds_msg}); kept PNG, "
                                   "which FO4 cannot load")
                # Mark this image as an addon-generated LOD texture so a
                # future re-run treats it as already-downscaled instead of
                # downscaling it again (see the fo4_lod_generated check
                # above this loop).
                new_img["fo4_lod_generated"] = True

                shared_cache[key] = new_img
                node.image = new_img
                processed += 1

    if processed == 0:
        msg = "No texture nodes with a source file found to downscale"
        if skipped:
            msg += " (" + "; ".join(skipped) + ")"
        return False, msg
    return True, (
        f"{len(shared_cache)} shared LOD texture(s) created, "
        f"applied to {processed} texture slot(s) across {len(lod_objects)} LOD object(s)"
        + (" -- " + "; ".join(skipped) if skipped else "")
    )


# ── Billboard LOD (the real FO4 farthest LOD level) ──────────────────────────

def generate_billboard_lod(source_obj, billboard_name: str, tex_size: int = 512) -> tuple:
    """Generate a baked-billboard LOD for *source_obj*.

    Real FO4 assets don't just keep decimating the organic mesh down for
    their farthest LOD level — verified against a real reference asset
    (``BlastedForestBurntTreeUpright01`` in the vanilla/DLC library): its
    last LOD level is 8 verts / 4 tris (two independent perpendicular quads —
    a classic "cross" billboard) using its own dedicated billboard texture,
    not the shared trunk atlas the closer LOD levels use.

    This renders a single front-view (looking down +Y, matching this addon's
    existing "front faces -Y" convention used elsewhere for facing-direction
    checks) orthographic capture of *source_obj* with a transparent
    background, builds that same 8-vert/4-tri cross shape sized to the
    object's bounding box, and applies the render to both quads via an
    alpha-clip material.

    Never modifies *source_obj* itself, and restores the scene's prior active
    camera / render engine / resolution / film_transparent afterward so this
    doesn't leave the user's scene in a different state.

    Returns (new_obj, message).
    """
    import os
    import tempfile
    from mathutils import Vector

    scene = bpy.context.scene

    corners = [source_obj.matrix_world @ Vector(c) for c in source_obj.bound_box]
    min_x = min(c.x for c in corners); max_x = max(c.x for c in corners)
    min_y = min(c.y for c in corners); max_y = max(c.y for c in corners)
    min_z = min(c.z for c in corners); max_z = max(c.z for c in corners)
    width = max(max_x - min_x, max_y - min_y, 1e-4)
    height = max(max_z - min_z, 1e-4)
    center_x = (min_x + max_x) * 0.5
    center_y = (min_y + max_y) * 0.5
    cam_distance = max(width, height) * 2.0 + 1.0

    # Save scene state so this is fully non-destructive to the user's setup.
    _prev_camera = scene.camera
    _prev_engine = scene.render.engine
    _prev_res_x = scene.render.resolution_x
    _prev_res_y = scene.render.resolution_y
    _prev_film_transparent = scene.render.film_transparent
    _prev_filepath = scene.render.filepath

    new_obj = None
    cam_obj = None
    bake_lights = []
    _hidden_prev = {}
    try:
        # ── Isolate the source object for this capture ─────────────────────
        # This billboard is meant to be a picture of ONE plant/object. When
        # Generate LOD0-LOD3 runs on a multi-object selection (e.g. every
        # plant in a cluster at once), every other mesh in the scene was
        # still fully visible during each object's render -- an orthographic
        # camera captures everything inside its view frustum along the whole
        # depth of the scene, not just whatever it's aimed at, so a
        # neighboring plant sitting anywhere in that frustum bled straight
        # into the "wrong" plant's billboard texture. Confirmed by a user
        # report: billboards showing parts of a different plant, sometimes a
        # completely different texture than the plant they're attached to.
        # Hiding every other render-visible object for the duration of this
        # one capture guarantees the render contains only *source_obj*, and
        # everything is restored to its prior visibility in the `finally`
        # block below.
        for _o in scene.objects:
            if _o is source_obj:
                continue
            if _o.hide_render:
                continue
            _hidden_prev[_o] = False
            _o.hide_render = True

        cam_data = bpy.data.cameras.new(f"{billboard_name}_BakeCam")
        cam_data.type = 'ORTHO'
        cam_data.ortho_scale = max(width, height) * 1.05
        cam_obj = bpy.data.objects.new(f"{billboard_name}_BakeCam", cam_data)
        scene.collection.objects.link(cam_obj)
        cam_obj.location = (center_x, min_y - cam_distance, (min_z + max_z) * 0.5)
        # Look down +Y ("front", matching this addon's -Y-facing-front convention).
        cam_obj.rotation_euler = (1.5707963267948966, 0.0, 0.0)
        scene.camera = cam_obj

        # ── Temporary bake lighting ────────────────────────────────────────
        # This capture used to rely entirely on whatever lights already
        # existed in the user's scene. Plenty of real scenes used for asset
        # work have no lights at all (or none pointed at this object from
        # this angle) -- when that happens the render comes back solid
        # black, and since film_transparent only affects the BACKGROUND
        # (the object itself is still fully opaque where it exists), the
        # baked billboard shows up as a flat black card instead of a
        # transparent silhouette of the source mesh. Confirmed from a user
        # screenshot: several fully opaque black rectangles floating around
        # an otherwise correctly-lit viewport. Adding a fixed 3-point rig
        # around the object for the duration of this one render guarantees a
        # correctly-lit capture regardless of what the user's scene has, and
        # it's removed again immediately after in the `finally` block below
        # so nothing about the user's scene is left changed.
        # SUN lights, not AREA: an area light's Watts are total radiant power
        # spread over its physical Size, so scaling `size` to the object's
        # bounding box (needed so the light actually covers it) makes a big
        # object's key light dimmer, not brighter, at the same energy value
        # -- irradiance = power / area. Confirmed as the actual cause of a
        # user report that the billboard was still too dark specifically on
        # a LARGE combined multi-object scene after the first lighting fix
        # (which used AREA lights) -- a small single-plant object looked
        # fine, a whole scene did not, exactly matching this scaling bug.
        # Sun lights measure strength as irradiance (W/m^2) directly and
        # don't fall off with distance or object size, so exposure stays
        # consistent regardless of how big *source_obj* is.
        _light_dist = cam_distance
        _rig = [
            ("Key",  (center_x, min_y - _light_dist, (min_z + max_z) * 0.5 + height * 0.3), 3.0),
            ("Fill", (max_x + _light_dist * 0.5, center_y, (min_z + max_z) * 0.5), 1.5),
            ("Rim",  (center_x, max_y + _light_dist * 0.5, max_z + height * 0.3), 2.0),
        ]
        for _label, _loc, _power in _rig:
            _ld = bpy.data.lights.new(f"{billboard_name}_Bake{_label}", type='SUN')
            _ld.energy = _power
            _ld.angle = 0.2  # slightly soft shadows, not a razor-sharp point-sun look
            _lo = bpy.data.objects.new(f"{billboard_name}_Bake{_label}", _ld)
            scene.collection.objects.link(_lo)
            _lo.location = _loc
            # Sun lights only care about rotation (direction), not location,
            # but keeping a real location makes the rig easy to inspect if
            # something goes wrong mid-bake. Point it from _loc toward the
            # object's center rather than reusing the camera's fixed
            # rotation, so the key/fill/rim actually aim at the subject from
            # each of their distinct positions instead of all three sharing
            # one straight-down-+Y direction.
            _to_center = Vector((center_x, center_y, (min_z + max_z) * 0.5)) - Vector(_loc)
            _lo.rotation_euler = _to_center.to_track_quat('-Z', 'Y').to_euler()
            bake_lights.append(_lo)

        for _engine in ('BLENDER_EEVEE_NEXT', 'BLENDER_EEVEE', 'CYCLES'):
            try:
                scene.render.engine = _engine
                break
            except Exception:
                continue
        scene.render.film_transparent = True
        scene.render.resolution_x = tex_size
        scene.render.resolution_y = tex_size

        out_path = os.path.join(tempfile.gettempdir(), f"{billboard_name}_billboard.png")
        scene.render.filepath = out_path
        scene.render.image_settings.file_format = 'PNG'
        scene.render.image_settings.color_mode = 'RGBA'
        bpy.ops.render.render(write_still=True)

        img = bpy.data.images.load(out_path, check_existing=False)
        img.name = f"{billboard_name}_d"

        # Cross billboard: two independent perpendicular quads (4 verts + 2
        # tris each = 8 verts / 4 tris total) -- matching the verified real
        # asset exactly, rather than a single flat card.
        half_w = width * 0.5
        mesh = bpy.data.meshes.new(billboard_name)
        verts = [
            (-half_w, 0.0, 0.0), (half_w, 0.0, 0.0), (half_w, 0.0, height), (-half_w, 0.0, height),
            (0.0, -half_w, 0.0), (0.0, half_w, 0.0), (0.0, half_w, height), (0.0, -half_w, height),
        ]
        faces = [(0, 1, 2, 3), (4, 5, 6, 7)]
        mesh.from_pydata(verts, [], faces)
        mesh.update()

        uv_layer = mesh.uv_layers.new(name="UVMap")
        quad_uv = [(0.0, 0.0), (1.0, 0.0), (1.0, 1.0), (0.0, 1.0)]
        for poly in mesh.polygons:
            for corner, loop_index in enumerate(poly.loop_indices):
                uv_layer.data[loop_index].uv = quad_uv[corner]

        new_obj = bpy.data.objects.new(billboard_name, mesh)
        scene.collection.objects.link(new_obj)
        new_obj.location = (center_x, center_y, min_z)

        mat = bpy.data.materials.new(f"{billboard_name}_Mat")
        mat.use_nodes = True
        mat.blend_method = 'CLIP'
        try:
            mat.shadow_method = 'CLIP'
        except AttributeError:
            pass  # removed in some Blender versions
        mat.use_backface_culling = False
        nodes = mat.node_tree.nodes
        links = mat.node_tree.links
        bsdf = next((n for n in nodes if n.type == 'BSDF_PRINCIPLED'), None)
        tex_node = nodes.new('ShaderNodeTexImage')
        tex_node.name = "Diffuse"
        tex_node.label = "Diffuse"
        tex_node.image = img
        if bsdf:
            links.new(tex_node.outputs['Color'], bsdf.inputs['Base Color'])
            alpha_input = bsdf.inputs.get('Alpha')
            if alpha_input:
                links.new(tex_node.outputs['Alpha'], alpha_input)
        new_obj.data.materials.append(mat)

        # fo4_mesh_type is a real RNA EnumProperty (bpy.types.Object.
        # fo4_mesh_type = EnumProperty(...)) -- obj["fo4_mesh_type"] = ...
        # (bracket/custom-property assignment) silently creates a SEPARATE,
        # unrelated custom property with the same name and never actually
        # touches the real RNA value the export pipeline reads via
        # getattr(obj, "fo4_mesh_type"). Must use attribute assignment.
        # Inherit the source's real category (e.g. 'VEGETATION') rather than
        # the inert 'LOD' tag nothing downstream checks for, matching the
        # fix in advanced_mesh_helpers.generate_lod_chain.
        try:
            new_obj.fo4_mesh_type = getattr(source_obj, 'fo4_mesh_type', '') or new_obj.fo4_mesh_type
        except Exception:
            pass
        new_obj["fo4_billboard"] = True
        new_obj["PYN_GAME"] = "FO4"
        # Built in the source's units (metres after an FO4 import), so it
        # needs the source's ×70 export tag too -- without it the exporter
        # guessed "already game units" and the billboard shipped at 1/70
        # size (22 units across for a 1,570-unit house, seen 2026-11-02).
        for _k in ("fo4_unit_scale", "fo4_scale_applied"):
            if _k in source_obj:
                new_obj[_k] = source_obj[_k]

        msg = (
            f"Billboard '{billboard_name}' generated: "
            f"{len(mesh.vertices)} verts / {len(mesh.polygons)*2} tris, "
            f"{tex_size}x{tex_size}px texture."
        )
        return new_obj, msg
    finally:
        if cam_obj is not None:
            bpy.data.objects.remove(cam_obj, do_unlink=True)
        for _lo in bake_lights:
            try:
                _ld = _lo.data
                bpy.data.objects.remove(_lo, do_unlink=True)
                if _ld is not None and _ld.users == 0:
                    bpy.data.lights.remove(_ld)
            except Exception:
                pass
        scene.camera = _prev_camera
        scene.render.engine = _prev_engine
        scene.render.resolution_x = _prev_res_x
        scene.render.resolution_y = _prev_res_y
        scene.render.film_transparent = _prev_film_transparent
        scene.render.filepath = _prev_filepath
        for _o, _prev_hide in _hidden_prev.items():
            try:
                _o.hide_render = _prev_hide
            except Exception:
                pass


