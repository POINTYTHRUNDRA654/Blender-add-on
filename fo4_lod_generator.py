def generate_lod_mesh(source_obj, ratio: float, lod_name: str) -> "tuple[object, str]":
    """
    Create a decimated copy of *source_obj* as a new object.

    Parameters
    ----------
    source_obj : Source Blender mesh object.
    ratio      : Decimate ratio (0.0–1.0, where 1.0 = original).
    lod_name   : Name for the new LOD object.

    Returns (new_obj, message).
    """
    # Duplicate
    new_mesh = source_obj.data.copy()
    new_obj  = source_obj.copy()
    new_obj.data = new_mesh
    new_obj.name = lod_name
    new_mesh.name = lod_name
    # The source's original NIF drives a post-export round-trip patch (root
    # name, BSXFlags, alpha) meant for that NIF, not for a LOD of it.
    if "fo4_source_nif" in new_obj:
        del new_obj["fo4_source_nif"]
    bpy.context.collection.objects.link(new_obj)

    # Explicitly carry material slots from source (handles both DATA- and
    # OBJECT-linked slots; ensures PyNifly-imported textures travel with the LOD)
    new_obj.data.materials.clear()
    for slot in source_obj.material_slots:
        new_obj.data.materials.append(slot.material)

    # Strip shape keys before decimating — Blender refuses to apply any
    # modifier to a mesh that has shape keys (RuntimeError).  LOD copies never
    # need shape keys (they are distance-based mesh replacements, not morphs).
    bpy.context.view_layer.objects.active = new_obj
    new_obj.select_set(True)
    if new_obj.data.shape_keys:
        try:
            bpy.ops.object.shape_key_remove(all=True)
        except Exception:
            pass

    # Apply decimate modifier
    mod = new_obj.modifiers.new("FO4_LOD_Decimate", 'DECIMATE')
    mod.decimate_type = 'COLLAPSE'
    mod.ratio = max(0.001, min(1.0, ratio))
    # use_collapse_triangulate=True forces triangulation before edge collapse,
    # which destroys quad flow on organic/plant meshes — leave it False.
    mod.use_collapse_triangulate = False
    mod.use_symmetry = False

    # Apply modifier. Check the result -- an unchecked CANCELLED here (e.g.
    # new_obj somehow isn't the active/context object at call time) would
    # leave the Decimate modifier un-applied while every triangle-count/
    # loose-vertex cleanup step below silently keeps running against the
    # full, un-decimated mesh and reports it as a successful LOD.
    bpy.context.view_layer.objects.active = new_obj
    _apply_result = bpy.ops.object.modifier_apply(modifier=mod.name)
    if 'FINISHED' not in _apply_result:
        print(f"[FO4 Add-on] LOD decimate modifier_apply did not finish for "
              f"'{new_obj.name}': {_apply_result} -- LOD mesh may still be at full density")

    # Decimate's COLLAPSE algorithm can strand vertices whose surrounding
    # faces all collapsed away without cleaning up the vertex itself --
    # worse at aggressive ratios (low LOD levels). Confirmed on a real asset:
    # loose-vertex count climbed with each more-aggressive LOD, visible as
    # holes/gaps in the mesh and propagating into any collision hull built
    # from it. Strip them here so every consumer of this LOD gets clean data.
    import bmesh as _bmesh
    _loose_bm = _bmesh.new()
    _loose_bm.from_mesh(new_obj.data)
    _loose_verts = [v for v in _loose_bm.verts if not v.link_faces]
    if _loose_verts:
        _bmesh.ops.delete(_loose_bm, geom=_loose_verts, context='VERTS')
        _loose_bm.to_mesh(new_obj.data)
        new_obj.data.update()
    _loose_bm.free()

    n_tris = sum(len(p.loop_indices) - 2 for p in new_obj.data.polygons)
    msg = (
        f"LOD '{lod_name}': {n_tris} triangles "
        f"({ratio*100:.0f}% of original)"
    )
    return new_obj, msg


def _world_bounds(obj):
    from mathutils import Vector
    pts = [obj.matrix_world @ Vector(c) for c in obj.bound_box]
    mn = Vector((min(p.x for p in pts), min(p.y for p in pts), min(p.z for p in pts)))
    mx = Vector((max(p.x for p in pts), max(p.y for p in pts), max(p.z for p in pts)))
    return mn, mx


def generate_lod_shell(source_obj, lod_name: str, target_tris: int,
                       voxel_div: int) -> "tuple[object, str]":
    """Build a LOD as one closed, simplified skin around *source_obj*.

    Decimate (generate_lod_mesh) works on clean hard-surface props but shreds
    meshes made of many thin or separate pieces -- a plant-covered building
    came out as loose floating shards at every level (seen 2026-11-02 on
    GSMutatedHouse01). Here the mesh is voxel-remeshed first, which fuses the
    pieces into one surface and drops detail thinner than a voxel, then small
    leftover islands are removed and the skin is decimated to *target_tris*
    and given fresh UVs for bake_lod_textures.

    Returns (new_obj, message), or (None, reason) when the remesh lost the
    object's shape (e.g. a long thin fence thinner than one voxel) so the
    caller can fall back to plain decimation.
    """
    import bmesh as _bmesh
    import math as _math

    mn, mx = _world_bounds(source_obj)
    diag = (mx - mn).length
    if diag <= 0:
        return None, "object has no size"
    voxel = diag / max(4, int(voxel_div))

    new_mesh = source_obj.data.copy()
    new_obj = source_obj.copy()
    new_obj.data = new_mesh
    new_obj.name = lod_name
    new_mesh.name = lod_name
    for _k in ("fo4_source_nif",):
        if _k in new_obj:
            del new_obj[_k]
    bpy.context.collection.objects.link(new_obj)
    new_obj.modifiers.clear()
    new_obj.vertex_groups.clear()
    if new_obj.data.shape_keys:
        new_obj.shape_key_clear()

    def _apply(mod):
        bpy.ops.object.select_all(action='DESELECT')
        bpy.context.view_layer.objects.active = new_obj
        new_obj.select_set(True)
        return bpy.ops.object.modifier_apply(modifier=mod.name)

    # Thicken first: a voxel remesh needs volume, and a thin open sheet (a
    # cliff face) thinner than one voxel simply vanished while the chunky
    # spores on it survived -- Billy's merged GSDirtCliffLarge01 LOD came out
    # "only the plants" (2026-11-09: the 41-unit cliff piece kept 28.6% of
    # its vertices on the LOD1 shell, another piece 0%).
    sd = new_obj.modifiers.new("FO4_LOD_Solidify", 'SOLIDIFY')
    sd.thickness = voxel * 1.5
    sd.offset = 0.0
    # NOT even thickness: on thin, sharp-cornered plant cards it pushed spikes
    # out hundreds of units (a test shell's bounding sphere grew from ~1,440
    # to 10,373 game units, 2026-11-09).
    sd.use_even_offset = False
    _apply(sd)

    rm = new_obj.modifiers.new("FO4_LOD_Remesh", 'REMESH')
    rm.mode = 'VOXEL'
    rm.voxel_size = voxel
    if 'FINISHED' not in _apply(rm):
        bpy.data.objects.remove(new_obj, do_unlink=True)
        return None, "voxel remesh did not run"

    bm = _bmesh.new()
    bm.from_mesh(new_obj.data)
    bm.faces.ensure_lookup_table()
    islands, seen = [], set()
    for f in bm.faces:
        if f.index in seen:
            continue
        stack, isle = [f], []
        seen.add(f.index)
        while stack:
            cur = stack.pop()
            isle.append(cur)
            for e in cur.edges:
                for nf in e.link_faces:
                    if nf.index not in seen:
                        seen.add(nf.index)
                        stack.append(nf)
        islands.append(isle)
    total = len(bm.faces)
    small = [f for isle in islands if len(isle) < 0.01 * total for f in isle]
    if small and len(small) < total:
        _bmesh.ops.delete(bm, geom=small, context='FACES')
    bm.to_mesh(new_obj.data)
    bm.free()
    new_obj.data.update()

    rmn, rmx = _world_bounds(new_obj)
    if not new_obj.data.polygons or any(
            (rmx[i] - rmn[i]) < 0.6 * (mx[i] - mn[i]) for i in range(3)):
        bpy.data.objects.remove(new_obj, do_unlink=True)
        return None, (f"voxel remesh at {voxel:.3g} lost the shape "
                      "(parts thinner than one voxel)")
    # Nor may the shell stick out past the source (spikes from thickening).
    if any((mn[i] - rmn[i]) > 3 * voxel or (rmx[i] - mx[i]) > 3 * voxel for i in range(3)):
        bpy.data.objects.remove(new_obj, do_unlink=True)
        return None, f"voxel remesh at {voxel:.3g} grew past the model's bounds"
    # The bounding box alone is not enough: plants spread over a cliff keep
    # the box while the cliff itself is gone. Check how much of the source's
    # SURFACE AREA the shell still covers.
    cov = _surface_coverage(source_obj, new_obj, 2.5 * voxel)
    if cov < _SHELL_MIN_COVERAGE:
        bpy.data.objects.remove(new_obj, do_unlink=True)
        return None, (f"voxel remesh at {voxel:.3g} kept only {cov:.0%} of the surface "
                      "(thin parts lost)")

    tris_now = len(new_obj.data.polygons) * 2  # remesh output is quads
    if tris_now > target_tris:
        dm = new_obj.modifiers.new("FO4_LOD_Decimate", 'DECIMATE')
        dm.decimate_type = 'COLLAPSE'
        dm.ratio = max(0.001, target_tris / tris_now)
        _apply(dm)

    bpy.ops.object.select_all(action='DESELECT')
    bpy.context.view_layer.objects.active = new_obj
    new_obj.select_set(True)
    bpy.ops.object.mode_set(mode='EDIT')
    bpy.ops.mesh.select_all(action='SELECT')
    bpy.ops.mesh.quads_convert_to_tris()
    bpy.ops.uv.smart_project(angle_limit=_math.radians(66), island_margin=0.003)
    bpy.ops.object.mode_set(mode='OBJECT')
    for poly in new_obj.data.polygons:
        poly.use_smooth = True

    new_obj["fo4_lod_voxel"] = voxel
    n_tris = len(new_obj.data.polygons)
    return new_obj, (f"LOD '{lod_name}': {n_tris} triangles "
                     f"(solid shell, voxel {voxel:.3g})")


# Share of the source's surface area a LOD1 shell must still cover. The
# thickened GSDirtCliffLarge01 shell covers 84% (cliff piece 96%); without the
# thickening the cliff piece kept under 30% and the LOD showed "only the plants".
_SHELL_MIN_COVERAGE = 0.80


def _surface_coverage(source_obj, shell_obj, max_dist: float) -> float:
    """Share of *source_obj*'s surface AREA lying within *max_dist* of
    *shell_obj* (both in world space): 1.0 = nothing lost."""
    import bmesh as _bmesh
    from mathutils.bvhtree import BVHTree
    bm = _bmesh.new()
    bm.from_mesh(shell_obj.data)
    bm.transform(shell_obj.matrix_world)
    bvh = BVHTree.FromBMesh(bm)
    bm.free()
    mw = source_obj.matrix_world
    total = near = 0.0
    for poly in source_obj.data.polygons:
        a = poly.area
        if a <= 0:
            continue
        total += a
        hit = bvh.find_nearest(mw @ poly.center)
        if hit[0] is not None and hit[3] <= max_dist:
            near += a
    return near / total if total > 0 else 1.0


def reduce_lod_shell(prev_obj, lod_name: str, target_tris: int) -> "tuple[object, str]":
    """Next, coarser LOD made by decimating the previous level's shell.

    At the coarser voxel sizes of LOD2/LOD3 a remesh can lose a thin open
    surface entirely (a cliff face with plants on it, 2026-11-09: LOD1's
    shell worked, LOD2 and LOD3 fell back to plain Decimate, which kept the
    merged source's three materials and wrote downscaled copies of every
    source texture while the exported LOD used only the cliff one). The
    previous shell is already one fused surface, so reducing it keeps every
    level a single-material, baked LOD.
    """
    import math as _math
    new_obj = prev_obj.copy()
    new_obj.data = prev_obj.data.copy()
    new_obj.name = lod_name
    new_obj.data.name = lod_name
    bpy.context.collection.objects.link(new_obj)
    new_obj.modifiers.clear()
    tris_now = len(new_obj.data.polygons)
    bpy.ops.object.select_all(action='DESELECT')
    bpy.context.view_layer.objects.active = new_obj
    new_obj.select_set(True)
    if tris_now > target_tris:
        dm = new_obj.modifiers.new("FO4_LOD_Decimate", 'DECIMATE')
        dm.decimate_type = 'COLLAPSE'
        dm.ratio = max(0.001, target_tris / tris_now)
        bpy.ops.object.modifier_apply(modifier=dm.name)
    bpy.ops.object.mode_set(mode='EDIT')
    bpy.ops.mesh.select_all(action='SELECT')
    bpy.ops.mesh.quads_convert_to_tris()
    bpy.ops.uv.smart_project(angle_limit=_math.radians(66), island_margin=0.003)
    bpy.ops.object.mode_set(mode='OBJECT')
    for poly in new_obj.data.polygons:
        poly.use_smooth = True
    n_tris = len(new_obj.data.polygons)
    return new_obj, (f"LOD '{lod_name}': {n_tris} triangles "
                     f"(reduced from {prev_obj.name}'s shell)")


def _reuv_for_bake(lod_obj) -> None:
    """Fresh, non-overlapping UVs on a decimated LOD so several source
    materials can be baked onto one texture (the source's own UVs overlap
    between materials)."""
    import math as _math
    bpy.ops.object.select_all(action='DESELECT')
    bpy.context.view_layer.objects.active = lod_obj
    lod_obj.select_set(True)
    bpy.ops.object.mode_set(mode='EDIT')
    bpy.ops.mesh.select_all(action='SELECT')
    bpy.ops.uv.smart_project(angle_limit=_math.radians(66), island_margin=0.003)
    bpy.ops.object.mode_set(mode='OBJECT')


def _lod_source_meshes(objs) -> list:
    """The meshes a LOD run should use from *objs*: no collision objects
    (PyNifly's "bhkPhysicsSystem", UCX_ hulls) and no earlier LOD output."""
    return [o for o in objs if getattr(o, "type", "") == 'MESH'
            and not o.name.lower().startswith(("ucx_", "bhk"))
            and not o.get("fo4_lod_level") and not o.get("fo4_billboard")]


def _model_name(pieces, active=None) -> str:
    """Name of the model the selected pieces come from: the NIF they were
    imported from when known (GSDirtCliffLarge01.nif -> GSDirtCliffLarge01),
    else the active piece's name without PyNifly's ':02' / '.001' suffixes."""
    order = ([active] if active is not None else []) + list(pieces)
    for o in order:
        src = o.get("fo4_source_nif") if o is not None else None
        if src:
            return os.path.splitext(os.path.basename(str(src)))[0]
    base = (active or (pieces[0] if pieces else None))
    name = base.name if base is not None else "Model"
    name = re.split(r"[:]", name)[0]
    name = re.sub(r"\.\d{3}$", "", name).strip()
    return name or "Model"


def merge_copies_for_lod(pieces, model_name: str):
    """One temporary mesh joined from COPIES of *pieces* (the pieces
    themselves are not touched), placed where they sit in the world, for a
    single LOD set of a multi-piece model. Caller removes it afterwards."""
    copies = []
    for o in pieces:
        c = o.copy()
        c.data = o.data.copy()
        bpy.context.scene.collection.objects.link(c)
        mw = o.matrix_world.copy()
        c.parent = None
        c.matrix_world = mw
        c.modifiers.clear()
        if c.data.shape_keys:
            c.shape_key_clear()
        copies.append(c)
    bpy.ops.object.select_all(action='DESELECT')
    for c in copies:
        c.select_set(True)
    bpy.context.view_layer.objects.active = copies[0]
    if len(copies) > 1:
        bpy.ops.object.join()
    merged = bpy.context.view_layer.objects.active
    merged.name = model_name + "_LODSource"
    merged.data.name = merged.name
    merged["fo4_lod_basename"] = model_name
    merged["fo4_lod_merged_tmp"] = True
    for k in ("fo4_source_nif",):
        if k in merged:
            del merged[k]
    return merged


def _lod_rel_dir(source_mat, fallback_sub: str) -> str:
    """Folder under Materials\\LOD\\ and Textures\\LOD\\ for an asset's LOD
    files, matching vanilla (materials\\LOD\\Architecture\\Skybridge\\...,
    LOD\\Architecture\\Shacks\\ShackLOD01_d.dds): the Mesh Sub-path the user
    typed, else the source material's own folder under Materials\\.

    The typed sub-path wins: a merged model's "active" material is just the
    first slot, so a cliff with grass and plant pieces put its LOD textures
    under Grass or Plants depending on slot order (2026-11-09)."""
    typed = "\\".join(p for p in re.split(r"[\\/]+", fallback_sub or "") if p)
    if typed:
        return typed
    name = (source_mat.get("BSLSP_Shader_Name", "") if source_mat else "") or ""
    parts = [p for p in re.split(r"[\\/]+", name) if p]
    if len(parts) >= 2 and parts[0].lower() == "materials":
        return "\\".join(parts[1:-1])
    return "\\".join(p for p in re.split(r"[\\/]+", fallback_sub or "") if p)


def _flat_image(name, size, rgba):
    img = bpy.data.images.new(name, size, size, alpha=False)
    img.generated_color = rgba
    return img


def _average_color(img):
    try:
        small = img.copy()
        small.scale(1, 1)
        px = tuple(small.pixels[:4])
        bpy.data.images.remove(small)
        return (px[0], px[1], px[2], 1.0)
    except Exception:
        return (0.25, 0.25, 0.25, 1.0)


def base_color_image(mat):
    """The colour image of *mat*: whatever image feeds the shader's base
    colour (Principled "Base Color", or the FO4 node group's "Diffuse"),
    else an image node named like a colour map. Imports differ: PyNifly
    names its node "Diffuse_Texture", Blender's glTF importer labels it
    "BASE COLOR" -- matching only "diffuse" baked a glTF mesh white
    (2026-11-05)."""
    if not mat or not mat.use_nodes or not mat.node_tree:
        return None
    nt = mat.node_tree

    def upstream_image(sock, depth=0):
        for link in sock.links:
            node = link.from_node
            if node.type == 'TEX_IMAGE' and node.image:
                return node.image
            if depth < 6:
                for inp in node.inputs:
                    img = upstream_image(inp, depth + 1)
                    if img:
                        return img
        return None

    for node in nt.nodes:
        for name in ("Base Color", "Diffuse", "Color"):
            sock = node.inputs.get(name) if node.type in ('BSDF_PRINCIPLED', 'GROUP', 'BSDF_DIFFUSE') else None
            if sock is not None and sock.is_linked:
                img = upstream_image(sock)
                if img:
                    return img
    for node in nt.nodes:
        if node.type == 'TEX_IMAGE' and node.image:
            key = (node.label + " " + node.name + " " + node.image.name).lower()
            if any(k in key for k in ("diffuse", "base color", "basecolor", "albedo", "_d.", "_d ")):
                return node.image
    return None


def bake_lod_textures(source_obj, lod_obj, tex_size: int, textures_root: str,
                      rel_dir: str, base: str) -> "tuple[dict, list]":
    """Bake *source_obj*'s diffuse colour and surface shape onto *lod_obj*'s
    own UVs (Cycles, selected-to-active) and save them as DDS in
    <textures_root>\\LOD\\<rel_dir>\\<base>_d/_n/_s.dds.

    Returns ({'Diffuse': path, 'Normal': path, 'Specular': path}, notes).
    A slot whose DDS conversion failed keeps its PNG and says so in notes --
    FO4 cannot load PNG, so the caller reports it instead of claiming success.
    """
    import os as _os
    import tempfile as _tf
    from . import nvtt_helpers as _nv

    scene = bpy.context.scene
    mn, mx = _world_bounds(lod_obj)
    span = (mx - mn).length
    out_dir = _os.path.join(textures_root, "LOD", *[p for p in rel_dir.split("\\") if p])
    _os.makedirs(out_dir, exist_ok=True)

    _diffuse_of = base_color_image

    # Bake through plain stand-in materials: the imported FO4 node group
    # bakes solid black in Cycles (seen 2026-11-02 on GSMutatedHouse01).
    # Originals go back in the finally block below.
    orig_slot_mats = [slot.material for slot in source_obj.material_slots]
    stand_ins = []
    src_diffuse = None
    for slot in source_obj.material_slots:
        img = _diffuse_of(slot.material)
        src_diffuse = src_diffuse or img
        sm = bpy.data.materials.new(f"{base}_src_bake")
        sm.use_nodes = True
        bsdf = next(n for n in sm.node_tree.nodes if n.type == 'BSDF_PRINCIPLED')
        if img is not None:
            tn = sm.node_tree.nodes.new('ShaderNodeTexImage')
            tn.image = img
            sm.node_tree.links.new(tn.outputs['Color'], bsdf.inputs['Base Color'])
        stand_ins.append(sm)
    fill = _average_color(src_diffuse) if src_diffuse else (0.25, 0.25, 0.25, 1.0)

    images = {
        "Diffuse": _flat_image(f"{base}_d", tex_size, fill),
        "Normal": _flat_image(f"{base}_n", tex_size, (0.5, 0.5, 1.0, 1.0)),
    }
    images["Normal"].colorspace_settings.name = 'Non-Color'

    bake_mat = bpy.data.materials.new(f"{base}_bake")
    bake_mat.use_nodes = True
    tnode = bake_mat.node_tree.nodes.new('ShaderNodeTexImage')
    bake_mat.node_tree.nodes.active = tnode
    lod_obj.data.materials.clear()
    lod_obj.data.materials.append(bake_mat)

    saved = dict(engine=scene.render.engine, sel=list(bpy.context.selected_objects),
                 active=bpy.context.view_layer.objects.active,
                 hide_src=source_obj.hide_render, hide_lod=lod_obj.hide_render)
    b = scene.render.bake
    saved_bake = {k: getattr(b, k) for k in (
        "use_selected_to_active", "use_cage", "cage_extrusion", "max_ray_distance",
        "margin", "use_pass_direct", "use_pass_indirect", "use_pass_color",
        "normal_space", "normal_r", "normal_g", "normal_b")}
    notes = []
    try:
        for slot, sm in zip(source_obj.material_slots, stand_ins):
            slot.material = sm
        scene.render.engine = 'CYCLES'
        saved["samples"] = scene.cycles.samples
        scene.cycles.samples = 8
        source_obj.hide_render = False
        lod_obj.hide_render = False
        bpy.ops.object.select_all(action='DESELECT')
        source_obj.select_set(True)
        lod_obj.select_set(True)
        bpy.context.view_layer.objects.active = lod_obj
        b.use_selected_to_active = True
        b.use_cage = False
        # The shell sits within about one voxel of the original surface. Rays
        # starting much further out than that hit the outermost spikes first
        # (span/40 baked 63% near-black on GSMutatedHouse01 vs 25% at this).
        voxel = float(lod_obj.get("fo4_lod_voxel", span / 50.0))
        b.cage_extrusion = voxel * 1.5
        b.max_ray_distance = voxel * 4.0
        b.margin = max(2, tex_size // 128)

        tnode.image = images["Diffuse"]
        b.use_pass_direct = False
        b.use_pass_indirect = False
        b.use_pass_color = True
        bpy.ops.object.bake(type='DIFFUSE')

        tnode.image = images["Normal"]
        b.normal_space = 'TANGENT'
        # FO4 normal maps are DirectX-style (green flipped vs Blender's OpenGL),
        # same convention as fo4_unity_converter / fo4_ue5_converter.
        b.normal_r, b.normal_g, b.normal_b = 'POS_X', 'NEG_Y', 'POS_Z'
        bpy.ops.object.bake(type='NORMAL')
    finally:
        for k, v in saved_bake.items():
            try:
                setattr(b, k, v)
            except Exception:
                pass
        if "samples" in saved:
            scene.cycles.samples = saved["samples"]
        scene.render.engine = saved["engine"]
        source_obj.hide_render = saved["hide_src"]
        lod_obj.hide_render = saved["hide_lod"]
        bpy.ops.object.select_all(action='DESELECT')
        for o in saved["sel"]:
            try:
                o.select_set(True)
            except Exception:
                pass
        bpy.context.view_layer.objects.active = saved["active"]
        lod_obj.data.materials.clear()
        bpy.data.materials.remove(bake_mat)
        for slot, om in zip(source_obj.material_slots, orig_slot_mats):
            slot.material = om
        for sm in stand_ins:
            bpy.data.materials.remove(sm)

    # Specular: R = specular, G = smoothness. A dull, flat map -- LOD is seen
    # from far away, and the source's own _s layout no longer matches these UVs.
    images["Specular"] = _flat_image(f"{base}_s", 64, (0.1, 0.15, 0.0, 1.0))

    paths = {}
    tmp = _tf.mkdtemp(prefix="fo4lod_")
    for slot, suffix in (("Diffuse", "_d"), ("Normal", "_n"), ("Specular", "_s")):
        img = images[slot]
        png = _os.path.join(tmp, f"{base}{suffix}.png")
        img.filepath_raw = png
        img.file_format = 'PNG'
        img.save()
        dds = _os.path.join(out_dir, f"{base}{suffix}.dds")
        try:
            ok, msg = _nv.NVTTHelpers.convert_to_dds(png, dds, slot=slot)
        except Exception as exc:
            ok, msg = False, str(exc)
        if ok and _os.path.isfile(dds):
            bpy.data.images.remove(img)
            paths[slot] = dds
        else:
            keep = _os.path.join(out_dir, f"{base}{suffix}.png")
            import shutil as _sh
            _sh.copy2(png, keep)
            bpy.data.images.remove(img)
            paths[slot] = keep
            notes.append(f"{base}{suffix}: DDS conversion failed ({msg}); saved PNG, "
                         "which FO4 cannot load -- set texconv in the add-on preferences")
    return paths, notes


_LOD_DROP_FLAGS = {
    # Wind: a LOD never sways (a merged cliff whose first material was a
    # swaying grass piece exported its LODs with Tree_Anim on, 2026-11-09).
    # Vertex alpha: LODs carry no vertex colours.
    # Glow: LODs do not glow (Billy, 2026-11-09; his first LODs had Glow_Map
    # on and the Decimate path wrote downscaled _g textures).
    "Shader_Flags_1": ("VERTEX_ALPHA", "OWN_EMIT", "EXTERNAL_EMITTANCE"),
    "Shader_Flags_2": ("TREE_ANIM", "GLOW_MAP"),
}


# Bit values of the dropped flags (PyNifly nifconstants ShaderFlags1/2).
_FLAG_BITS = {
    "Shader_Flags_1": {"VERTEX_ALPHA": 1 << 3, "OWN_EMIT": 1 << 22, "EXTERNAL_EMITTANCE": 1 << 29},
    "Shader_Flags_2": {"TREE_ANIM": 1 << 29, "GLOW_MAP": 1 << 6},
}


def _clean_mesh_subpath(text: str) -> str:
    """Mesh Sub-path as the part under Meshes\\ (without a leading LOD).

    A full folder path typed or pasted into the field
    (C:\\Users\\...\\Downloads\\Meshes\\LOD\\Landscape) was joined as-is: the
    NIFs still landed right, but the .bgsm and textures went to
    Materials\\LOD\\Users\\Owner\\Downloads\\Meshes\\LOD\\Landscape and every
    NIF's material path started with "materials\\LOD\\C:\\..." (2026-11-09)."""
    parts = [p for p in re.split(r"[\\/]+", text or "") if p]
    low = [p.lower() for p in parts]
    if "meshes" in low:
        parts = parts[len(low) - 1 - low[::-1].index("meshes") + 1:]
    elif parts and (parts[0].endswith(":") or (text or "").startswith(("\\\\", "//"))):
        parts = parts[-1:]                 # some other absolute path: keep its last folder
    if parts and parts[0].upper() == "LOD":
        parts = parts[1:]
    return "/".join(parts)


def _is_glow_node(node) -> bool:
    label = f"{node.label} {node.name}".lower()
    img = getattr(node, "image", None)
    stem = ""
    if img is not None:
        stem = os.path.splitext(os.path.basename(img.filepath or img.name))[0].lower()
    return "glow" in label or stem.endswith("_g")


def strip_lod_material(mat) -> None:
    """Make *mat* a LOD material: no wind, no vertex alpha, no glow.

    Removes those shader flags from PyNifly's Shader_Flags_1/2 text, the
    wind request, the glow texture slot and every glow image node, so
    neither the NIF nor the .bgsm (see blender_mat_to_bgsm's is_lod) asks
    for wind or a glow map."""
    if mat is None:
        return

    def _strip(val, key):
        if not isinstance(val, str):
            return val
        if val.strip().isdigit():          # numeric flag word
            n = int(val.strip())
            for name in _LOD_DROP_FLAGS[key]:
                n &= ~_FLAG_BITS[key].get(name, 0)
            return str(n)
        return " | ".join(t.strip() for t in val.split("|")
                          if t.strip() and t.strip().upper() not in _LOD_DROP_FLAGS[key])

    # Older PyNifly: custom properties. PyNifly 30.2 (Billy's Blender 5.1):
    # material.pyn_shader.Shader_Flags_1/2, which is what its exporter reads
    # (shader_io._export_shader_attrs -> pyn_props.shader_store). Stripping
    # only the custom property left Glow_Map on the exported LODs.
    for key in _LOD_DROP_FLAGS:
        if key in mat:
            mat[key] = _strip(mat.get(key), key)
    grp = getattr(mat, "pyn_shader", None)
    if grp is not None:
        for key in _LOD_DROP_FLAGS:
            try:
                val = getattr(grp, key, None)
                if isinstance(val, str):
                    setattr(grp, key, _strip(val, key))
            except Exception:
                pass
    for k in ("fo4_bgsm_tree", "fo4_bgsm_name_before_wind", "BSShaderTextureSet_Glow"):
        if k in mat:
            del mat[k]
    if getattr(mat, "use_nodes", False) and mat.node_tree:
        for n in [n for n in mat.node_tree.nodes if n.type == 'TEX_IMAGE' and _is_glow_node(n)]:
            mat.node_tree.nodes.remove(n)


def make_lod_material(source_mat, lod_obj, tex_paths: dict, bgsm_rel: str,
                      opaque: bool) -> "object":
    """Give *lod_obj* its own copy of *source_mat* pointing at the LOD
    textures and at its own materials\\LOD\\... .bgsm.

    The NIF's material name decides which .bgsm the game and LOD generators
    read, and a .bgsm overrides the NIF's texture slots -- so a LOD that kept
    the source's material name would still draw the full-size 4K textures no
    matter what the NIF itself references (found on 2026-11-02's house LODs).
    """
    import os as _os
    mat = source_mat.copy() if source_mat else bpy.data.materials.new(lod_obj.name)
    mat.name = _os.path.splitext(_os.path.basename(bgsm_rel))[0]
    mat["BSLSP_Shader_Name"] = bgsm_rel
    if "fo4_bgsm_path" in mat:
        del mat["fo4_bgsm_path"]
    if "BSShaderTextureSet_RootMaterialPath" in mat:
        del mat["BSShaderTextureSet_RootMaterialPath"]
    strip_lod_material(mat)
    if not mat.use_nodes:
        mat.use_nodes = True
    nodes = mat.node_tree.nodes
    for slot, path in tex_paths.items():
        rel = path.replace("/", "\\")
        idx = rel.lower().rfind("\\textures\\")
        rel = rel[idx + len("\\textures\\"):] if idx >= 0 else _os.path.basename(rel)
        mat[f"BSShaderTextureSet_{slot}"] = rel
        node = next((n for n in nodes if n.type == 'TEX_IMAGE'
                     and slot.lower() in (n.label or n.name).lower()), None)
        if node is None:
            node = nodes.new('ShaderNodeTexImage')
            node.name = node.label = f"{slot}_Texture"
        node.image = bpy.data.images.load(path, check_existing=True)
        if slot != "Diffuse":
            node.image.colorspace_settings.name = 'Non-Color'
    if opaque:
        for n in [n for n in nodes if n.type == 'GROUP' and "alpha" in (n.label or n.name).lower()]:
            nodes.remove(n)
        if "pyn_synthetic_alpha_from_bgsm" in mat:
            del mat["pyn_synthetic_alpha_from_bgsm"]
        mat.blend_method = 'OPAQUE'
    lod_obj.data.materials.clear()
    lod_obj.data.materials.append(mat)
    return mat


def resolve_mod_root(folder: str) -> "tuple[str, str]":
    """The MO2 mod folder itself when *folder* points inside it.

    Picking the mod's Textures\\LOD folder as the output (an easy slip, since
    that is where LOD textures end up) wrote Meshes\\ and Textures\\ trees
    INSIDE Textures\\LOD\\, where nothing loads them (seen 2026-11-02).
    Returns (root, note); note is '' when *folder* was already the root.
    """
    import os as _os
    norm = _os.path.normpath(folder)
    parts = norm.split(_os.sep)
    idx = next((i for i, p in enumerate(parts)
                if i > 0 and p.lower() in ("meshes", "textures", "materials")), None)
    if idx is None:
        return norm, ""
    root = _os.sep.join(parts[:idx])
    if len(parts[0]) == 2 and parts[0].endswith(":") and idx == 1:
        root += _os.sep
    return root, (f"Mod Output Folder pointed inside the mod ({parts[idx]}\\...); "
                  f"using the mod folder {root}")


# ── Texture baking setup ──────────────────────────────────────────────────────

def _create_bake_image(name: str, width: int, height: int,
                        is_data: bool = True) -> "bpy.types.Image":
    """Create (or reuse) a Blender image for baking."""
    if name in bpy.data.images:
        img = bpy.data.images[name]
        if img.size[0] != width or img.size[1] != height:
            img.scale(width, height)
        return img
    img = bpy.data.images.new(name, width=width, height=height, alpha=False)
    img.colorspace_settings.name = 'Non-Color' if is_data else 'sRGB'
    img.file_format = 'PNG'
    return img


def setup_bake_target_node(mat, img) -> None:
    """Add/select a TEX_IMAGE node in *mat* pointing at *img* for baking."""
    mat.use_nodes = True
    # Find or create the bake target node
    bake_node = mat.node_tree.nodes.get("FO4_BakeTarget")
    if not bake_node:
        bake_node = mat.node_tree.nodes.new('ShaderNodeTexImage')
        bake_node.name  = "FO4_BakeTarget"
        bake_node.label = "FO4 Bake Target"
        bake_node.location = (300, -400)
    bake_node.image = img
    # Select it (Blender bakes to the active/selected image node)
    mat.node_tree.nodes.active = bake_node


def prepare_normal_bake(low_obj, high_obj, tex_size: int = 2048,
                         ray_dist: float = 0.05) -> tuple:
    """
    Set up the scene for a high-to-low normal map bake.

    Selects high_obj + low_obj, configures Cycles bake settings.
    Returns (bake_image, message).

    The caller must then call bpy.ops.object.bake(type='NORMAL') to run it.
    """
    bpy.context.scene.render.engine = 'CYCLES'
    bpy.context.scene.cycles.bake_type = 'NORMAL'
    bpy.context.scene.render.bake.use_selected_to_active = True
    bpy.context.scene.render.bake.use_cage = True
    bpy.context.scene.render.bake.cage_extrusion = ray_dist
    bpy.context.scene.render.bake.normal_space = 'TANGENT'
    bpy.context.scene.render.bake.margin = max(4, tex_size // 256)

    img_name = f"{low_obj.name}_n_BAKED"
    bake_img = _create_bake_image(img_name, tex_size, tex_size, is_data=True)

    # Set bake target on every material of the low-poly
    for slot in low_obj.material_slots:
        if slot.material:
            setup_bake_target_node(slot.material, bake_img)

    # Select: high (active source), low (selected target)
    bpy.ops.object.select_all(action='DESELECT')
    high_obj.select_set(True)
    low_obj.select_set(True)
    bpy.context.view_layer.objects.active = low_obj  # bake TARGET = active

    return bake_img, (
        f"Normal bake ready: {img_name} ({tex_size}×{tex_size}px). "
        f"Ray distance: {ray_dist}. "
        "Click 'Bake' in Render Properties, then save the image."
    )


