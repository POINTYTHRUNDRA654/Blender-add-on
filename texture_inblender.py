"""Texture tools that work on images inside Blender.

Meshes being worked on often have textures that exist only inside the .blend
(packed, generated by a bake, or never saved). The Texture Helpers buttons
used to open a file browser and could not see those. These helpers let every
texture operator work on the active object's images directly:

* list the images on the active object, with their FO4 slot (Diffuse,
  Normal, Specular, Glow) when the material wiring tells us;
* write one to a temporary PNG with its stored pixel values unchanged (no
  colour management, so sRGB colour and Non-Color normal data both survive);
* run the real AI upscaler and check the size it actually produced;
* load results back as images packed into the .blend and plug them into the
  same material slot, keeping the old image in the file.

No operators live here; the operators in ai_gen_operators.py and
texture_enhance_helpers.py call these functions.
"""

import os
import tempfile

import bpy

SLOTS = ("Diffuse", "Normal", "Specular", "Glow")
NON_COLOR_SLOTS = {"Normal", "Specular", "Glow"}

# Dynamic EnumProperty items must stay referenced from Python, or Blender
# shows garbage labels (documented bpy gotcha).
_ENUM_CACHE = []


def _texture_helpers():
    try:
        from .texture_helpers import TextureHelpers
        return TextureHelpers
    except Exception:
        return None


def object_images(obj):
    """[(slot_or_None, material, node, image)] for every image node with an
    image on *obj*'s materials, each image once, slot images first."""
    out = []
    if obj is None or obj.type != 'MESH':
        return out
    th = _texture_helpers()
    seen = set()
    for mat in obj.data.materials:
        if not mat or not mat.use_nodes:
            continue
        slot_of = {}
        if th is not None:
            for slot in SLOTS:
                try:
                    n = th._find_slot_node(mat, slot)
                except Exception:
                    n = None
                if n is not None and n.image is not None:
                    slot_of.setdefault(n.name, slot)
        for node in mat.node_tree.nodes:
            if node.type != 'TEX_IMAGE' or node.image is None:
                continue
            img = node.image
            if img.name in seen:
                continue
            seen.add(img.name)
            out.append((slot_of.get(node.name), mat, node, img))
    order = {s: i for i, s in enumerate(SLOTS)}
    out.sort(key=lambda t: order.get(t[0], len(SLOTS)))
    return out


def image_enum_items(self, context):
    """EnumProperty items: images on the active object (slot images first)."""
    items = []
    obj = getattr(context, "active_object", None)
    for slot, mat, node, img in object_images(obj):
        w, h = img.size
        label = f"{slot}: {img.name}" if slot else img.name
        items.append((img.name, f"{label} ({w}x{h})", f"Material {mat.name}, node {node.name}"))
    if not items:
        items.append(("NONE", "(no textures on the active object)", ""))
    _ENUM_CACHE[:] = items
    return _ENUM_CACHE


def default_image_name(obj, prefer=("Diffuse",)):
    imgs = object_images(obj)
    for want in prefer:
        for slot, _m, _n, img in imgs:
            if slot == want:
                return img.name
    return imgs[0][3].name if imgs else ""


def find_image_on_object(obj, name):
    for slot, mat, node, img in object_images(obj):
        if img.name == name:
            return slot, mat, node, img
    return None


def work_dir():
    d = os.path.join(tempfile.gettempdir(), "fo4_addon_textures")
    os.makedirs(d, exist_ok=True)
    return d


def _safe(name):
    return "".join(c if (c.isalnum() or c in "_-") else "_" for c in name) or "image"


def image_to_png(img, folder=None, name=None):
    """Write *img*'s stored pixels to a PNG and return its path.

    Goes through a temporary image built from the raw pixel values, so the
    original image (packed or not) is never unpacked, re-pathed or changed,
    and no view transform is applied."""
    import numpy as np
    if img is None:
        raise ValueError("no image")
    w, h = img.size
    if w == 0 or h == 0:
        img.reload()
        w, h = img.size
    if w == 0 or h == 0:
        raise ValueError(f"Image '{img.name}' has no pixels (its file is missing and it is not packed)")
    folder = folder or work_dir()
    path = os.path.join(folder, (name or _safe(img.name)) + ".png")
    px = np.empty(w * h * 4, dtype=np.float32)
    img.pixels.foreach_get(px)
    tmp = bpy.data.images.new("__fo4_tmp_export", w, h, alpha=True, float_buffer=False)
    try:
        tmp.colorspace_settings.name = img.colorspace_settings.name
        tmp.pixels.foreach_set(px)
        tmp.filepath_raw = path
        tmp.file_format = 'PNG'
        tmp.save()
    finally:
        bpy.data.images.remove(tmp)
    if not os.path.isfile(path):
        raise OSError(f"Could not write {path}")
    return path


def png_size(path):
    try:
        from PIL import Image
        with Image.open(path) as im:
            return im.size
    except Exception:
        img = bpy.data.images.load(path, check_existing=False)
        try:
            return tuple(img.size)
        finally:
            bpy.data.images.remove(img)


def ai_upscale_png(src, dst, scale=4):
    """Upscale *src* to *dst* by *scale* (2 or 4).

    Uses the installed Real-ESRGAN (realesrgan-x4plus, always run at 4x; a 2x
    result is a high-quality downsize of the 4x one) and checks the size it
    really produced. Falls back to a plain Lanczos resize only when no AI
    upscaler works, and says so.

    Returns (ok, method, message): method is 'ai' or 'lanczos'."""
    w, h = png_size(src)
    want = (w * scale, h * scale)
    ai_err = ""
    try:
        from .realesrgan_helpers import RealESRGANHelpers as R
        if R.is_realesrgan_available():
            tmp4 = dst if scale == 4 else os.path.splitext(dst)[0] + "_x4tmp.png"
            ok, msg = R.upscale_texture(src, tmp4, 4)
            if ok and os.path.isfile(tmp4) and png_size(tmp4) == (w * 4, h * 4):
                if scale != 4:
                    from PIL import Image
                    with Image.open(tmp4) as im:
                        im.resize(want, Image.LANCZOS).save(dst)
                    os.remove(tmp4)
                return True, "ai", f"Real-ESRGAN {w}x{h} -> {want[0]}x{want[1]}"
            got = png_size(tmp4) if os.path.isfile(tmp4) else None
            ai_err = msg if not ok else f"Real-ESRGAN returned {got}, expected {(w * 4, h * 4)}"
        else:
            ai_err = "Real-ESRGAN is not installed (Setup & Status panel: Install AI Upscaler)"
    except Exception as e:
        ai_err = f"Real-ESRGAN failed: {e}"
    try:
        from PIL import Image
        with Image.open(src) as im:
            im.resize(want, Image.LANCZOS).save(dst)
        return True, "lanczos", f"plain Lanczos resize, NOT AI ({ai_err})"
    except Exception as e:
        return False, "none", f"Upscale failed: {ai_err}; Lanczos fallback failed: {e}"


def resize_png(src, dst, size):
    from PIL import Image
    with Image.open(src) as im:
        im.resize(tuple(size), Image.LANCZOS).save(dst)
    return dst


def load_png(path, name, colorspace='sRGB'):
    """Load *path* as a new image packed into the .blend, named *name*
    (an older image of that name gets a numbered name instead)."""
    img = bpy.data.images.load(path, check_existing=False)
    img.colorspace_settings.name = colorspace
    img.pack()
    img.name = name
    return img


def assign(obj, mat, node, img, slot=None):
    """Put *img* into *node* (or into the material's *slot* node, created and
    wired like 'Install Texture' does when missing). Returns the node."""
    if node is None and mat is not None and slot:
        th = _texture_helpers()
        if th is not None:
            node = th._find_slot_node(mat, slot) or th._ensure_texture_slot_node(mat, slot)
    if node is not None:
        node.image = img
    return node


def is_data_map(slot, img):
    return slot in NON_COLOR_SLOTS or img.colorspace_settings.name in ('Non-Color', 'Linear', 'Raw')


def upscale_object_image(obj, image_name, scale=4, apply=True, save_dir=""):
    """Upscale one image on *obj* inside Blender.

    Colour textures go through Real-ESRGAN. Normal maps and other data maps
    are resized with Lanczos (normals renormalised): an AI trained on photos
    would invent detail that breaks their values.
    Returns (ok, message, level, new_image)."""
    hit = find_image_on_object(obj, image_name)
    if not hit:
        return False, f"Texture '{image_name}' is not on the active object", 'ERROR', None
    slot, mat, node, img = hit
    w, h = img.size
    work = tempfile.mkdtemp(prefix="fo4_upscale_", dir=work_dir())
    src = image_to_png(img, work, _safe(img.name))
    dst = os.path.join(work, f"{_safe(img.name)}_x{scale}.png")
    if is_data_map(slot, img):
        if slot == "Normal":
            from .texture_enhance_helpers import _resize_normals
            _resize_normals(src, dst, (w * scale, h * scale))
            how = "normal map: Lanczos resize + renormalised (AI upscalers are for colour)"
        else:
            resize_png(src, dst, (w * scale, h * scale))
            how = "data map: Lanczos resize (AI upscalers are for colour)"
        method = "data"
    else:
        ok, method, how = ai_upscale_png(src, dst, scale)
        if not ok:
            return False, how, 'ERROR', None
    new = load_png(dst, f"{img.name}_x{scale}", img.colorspace_settings.name)
    if apply:
        assign(obj, mat, node, new)
    msg = f"{img.name}: {w}x{h} -> {new.size[0]}x{new.size[1]} ({how})"
    if apply:
        msg += "; now used on the object (old image kept in the .blend)"
    if save_dir:
        msg += f"; saved {save_copy(new, save_dir)}"
    level = 'WARNING' if method == "lanczos" else 'INFO'
    return True, msg, level, new


def save_copy(img, folder, filename=None):
    """Also write *img* to *folder* (for use outside Blender). Returns path."""
    folder = bpy.path.abspath(folder)
    os.makedirs(folder, exist_ok=True)
    return image_to_png(img, folder, os.path.splitext(filename or _safe(img.name))[0])
